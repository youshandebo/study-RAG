def tokenize(text: str) -> Iterator[str]:
    """将长文本切成拟真流式 token；LaTeX 公式块保持原子性不被切碎。"""
    pattern = re.compile(r"(\$\$[^$]*\$\$|\$[^$]*\$)")
    pos = 0
    for m in pattern.finditer(text):
        for i in range(pos, m.start(), 9):
            yield text[i : min(i + 9, m.start())]
        yield m.group(0)
        pos = m.end()
    for i in range(pos, len(text), 9):
        yield text[i : min(i + 9, len(text))]


